#!/usr/bin/env python3
"""Writes the launcher icon and the TV banner (vector drawables, transparent background).

    python3 tools/icon/make_icon.py        # needs fontTools (pip install fonttools)

The mark is three stacked cards (recent apps). The banner is the mark plus the wordmark, laid out like
other TV banners that show a logo and a name on a transparent tile. The wordmark is outlined
from the app's own font (app/src/main/res/font/manrope.ttf, OFL), so no text or font is needed at run time.
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res"
FONT = RES / "font/manrope.ttf"

# back → front; the front card is the app's accent green
TONES = ["@color/ic_launcher_foreground_tertiary", "@color/ic_launcher_foreground_secondary", "@color/ic_launcher_foreground_primary"]
MONO_ALPHA = ["0.40", "0.68", "1"]
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icon/make_icon.py -->\n'


def n(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def card(x, y, size, r):
    s = size - 2 * r
    return (f"M{n(x + r)},{n(y)} h{n(s)} a{n(r)},{n(r)} 0 0 1 {n(r)},{n(r)} v{n(s)} a{n(r)},{n(r)} 0 0 1 -{n(r)},{n(r)} "
            f"h-{n(s)} a{n(r)},{n(r)} 0 0 1 -{n(r)},-{n(r)} v-{n(s)} a{n(r)},{n(r)} 0 0 1 {n(r)},-{n(r)} z")


def mark(x, y, size, step, r, colors, alphas=None):
    """Three cards stepping down to the right from (x, y)."""
    out = []
    for i, c in enumerate(colors):
        alpha = f'\n        android:fillAlpha="{alphas[i]}"' if alphas else ""
        out.append(f'    <path\n        android:fillColor="{c}"{alpha}\n'
                   f'        android:pathData="{card(x + i * step, y + i * step, size, r)}" />\n')
    return "".join(out)


def vector(w, h, vw, vh, body):
    return (f'{HEADER}<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{w}dp"\n    android:height="{h}dp"\n'
            f'    android:viewportWidth="{vw}"\n    android:viewportHeight="{vh}">\n{body}</vector>\n')


def text_path(text, weight, cap_px, x, baseline, max_w=None):
    """SVG path data for [text] at [weight], capitals [cap_px] tall, starting at x on [baseline]; also its end x and real cap height."""
    font = instantiateVariableFont(TTFont(FONT), {"wght": weight})
    glyphs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    cap = font["OS/2"].sCapHeight
    advance = sum(hmtx[cmap[ord(c)]][0] for c in text)
    scale = cap_px / cap
    if max_w and advance * scale > max_w:
        scale = max_w / advance
    pen = SVGPathPen(glyphs, ntos=n)
    cx = x
    for c in text:
        name = cmap[ord(c)]
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, cx, baseline)))
        cx += hmtx[name][0] * scale
    return pen.getCommands(), cx, scale * cap


def write(rel, text):
    path = RES / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(ROOT))


# ── launcher icon: adaptive (108 dp canvas, the mark inside the 66 dp safe zone), transparent background ──
icon = dict(x=30, y=30, size=30, step=9, r=6.5)
write("drawable/ic_launcher_foreground.xml", vector(108, 108, 108, 108, mark(colors=TONES, **icon)))
write("drawable/ic_launcher_monochrome.xml", vector(108, 108, 108, 108, mark(colors=["#FFFFFFFF"] * 3, alphas=MONO_ALPHA, **icon)))
write("drawable/ic_launcher_background.xml", vector(
    108, 108, 108, 108,
    '    <path\n        android:fillColor="@color/ic_launcher_background"\n        android:pathData="M0,0h108v108h-108z" />\n'))
ADAPTIVE = (f'{HEADER}<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
            '</adaptive-icon>\n')
write("mipmap-anydpi-v26/ic_launcher.xml", ADAPTIVE)
write("mipmap-anydpi-v26/ic_launcher_round.xml", ADAPTIVE)
# Android 7 (no adaptive icons): the mark alone, a little larger
legacy = vector(48, 48, 48, 48, mark(x=6, y=6, size=22, step=7, r=5, colors=TONES))
write("mipmap-anydpi/ic_launcher.xml", legacy)
write("mipmap-anydpi/ic_launcher_round.xml", legacy)

# ── TV banner (320 × 180 px at xhdpi): mark on the left, "Recent Apps" beside it, nothing behind them ──
CAP = 28          # capital height wanted, px; narrowed if the name would pass MAX_W
MAX_W = 206
X = 102
_, _, cap = text_path("Recent Apps", 800, CAP, X, 0, max_w=MAX_W)       # the height it really gets
# one line, its capitals centred on the banner's middle (y = 90), level with the mark
name, end, _ = text_path("Recent Apps", 800, CAP, X, 90 + cap / 2, max_w=MAX_W)
banner = (mark(x=18, y=56, size=42, step=13, r=9, colors=TONES)
          + f'    <path\n        android:fillColor="#FFFFFFFF"\n        android:pathData="{name}" />\n')
write("drawable/tv_banner.xml", vector(160, 90, 320, 180, banner))
print(f"wordmark: capitals {cap:.1f} px, x {X} to {end:.1f}")
